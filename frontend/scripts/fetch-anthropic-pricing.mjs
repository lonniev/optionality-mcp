#!/usr/bin/env node
// Refresh src/data/anthropicPricing.generated.ts from OpenRouter's
// /api/v1/models endpoint. OpenRouter publishes Anthropic's per-token
// rates pass-through (no per-token markup), so this is a free, dynamic
// price oracle.
//
// Runs as a prebuild step. Network failures are NON-fatal: we keep the
// previously-generated snapshot so offline / CI-without-egress builds
// still succeed.
//
// Model id normalization:
//   OpenRouter:  anthropic/claude-opus-4.7
//   Anthropic:   claude-opus-4-7
// Strip the "anthropic/" prefix and swap dots for dashes. Both dotted
// and dashed aliases are emitted so a recorded model string from either
// surface resolves.

import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, "../src/data/anthropicPricing.generated.ts");
const SRC_URL = "https://openrouter.ai/api/v1/models";

function normalizeKey(openrouterId) {
  return openrouterId.replace(/^anthropic\//, "").replace(/\./g, "-");
}

async function fetchPricing() {
  const res = await fetch(SRC_URL, {
    headers: { "User-Agent": "optionality-mcp-prebuild/0.1" },
  });
  if (!res.ok) throw new Error(`OpenRouter ${res.status}`);
  const body = await res.json();
  const all = Array.isArray(body?.data) ? body.data : [];
  return all.filter((m) => typeof m?.id === "string" && m.id.startsWith("anthropic/"));
}

function emit(models) {
  const fetchedAt = new Date().toISOString();
  const entries = {};

  for (const m of models) {
    const promptRate = Number(m.pricing?.prompt);
    const completionRate = Number(m.pricing?.completion);
    if (!Number.isFinite(promptRate) || !Number.isFinite(completionRate)) continue;

    // OpenRouter rates are USD per token. Convert to USD per million
    // tokens so the consumer math stays readable. Round to 4 decimals
    // to strip IEEE-754 noise (e.g. 0.0000008 * 1e6 = 0.7999999…).
    const inputPerMtok = Math.round(promptRate * 1_000_000 * 1e4) / 1e4;
    const outputPerMtok = Math.round(completionRate * 1_000_000 * 1e4) / 1e4;

    const dashedKey = normalizeKey(m.id);
    const dottedKey = m.id.replace(/^anthropic\//, "");
    entries[dashedKey] = { input: inputPerMtok, output: outputPerMtok };
    if (dottedKey !== dashedKey) {
      entries[dottedKey] = { input: inputPerMtok, output: outputPerMtok };
    }
  }

  if (Object.keys(entries).length === 0) {
    throw new Error("No Anthropic models in OpenRouter response");
  }

  const banner = [
    "// AUTO-GENERATED by scripts/fetch-anthropic-pricing.mjs. Do not edit by hand.",
    "// Source: OpenRouter /api/v1/models (pass-through Anthropic rates).",
    `// Fetched: ${fetchedAt}`,
    "",
    "export type ModelRate = { input: number; output: number };",
    "",
    `export const PRICING_FETCHED_AT = "${fetchedAt}";`,
    `export const PRICING_SOURCE = "openrouter:/api/v1/models";`,
    "",
    "// USD per million tokens. Keyed by both dashed (Anthropic API) and",
    "// dotted (OpenRouter) model ids so either string resolves.",
    "export const MODEL_PRICING: Record<string, ModelRate> = " +
      JSON.stringify(entries, null, 2) +
      ";",
    "",
  ].join("\n");

  writeFileSync(OUT_PATH, banner);
  console.log(`[anthropic-pricing] wrote ${Object.keys(entries).length} entries → ${OUT_PATH}`);
}

try {
  const models = await fetchPricing();
  emit(models);
} catch (err) {
  if (existsSync(OUT_PATH)) {
    const prior = readFileSync(OUT_PATH, "utf8");
    const m = prior.match(/Fetched: (.+)/);
    console.warn(
      `[anthropic-pricing] refresh failed (${err.message}); keeping prior snapshot from ${m?.[1] ?? "unknown"}.`
    );
  } else {
    console.error(`[anthropic-pricing] refresh failed and no prior snapshot: ${err.message}`);
    process.exit(1);
  }
}
